// Vmess is the base struct of vmess link
type Vmess struct {
	Tag      string `json:"tag,omitempty"`
	Server   string `json:"server,omitempty"`
	Port     uint16 `json:"port,omitempty"`
	UUID     string `json:"uuid,omitempty"`
	AlterID  int    `json:"alterId,omitempty"`
	Security string `json:"security,omitempty"`

	Transport string `json:"transport,omitempty"`
	Host      string `json:"host,omitempty"`
	Path      string `json:"path,omitempty"`

	TLS           bool     `json:"tls,omitempty"`
	SNI           string   `json:"sni,omitempty"`
	ALPN          []string `json:"alpn,omitempty"`
	AllowInsecure bool     `json:"allowInsecure,omitempty"`
	Fingerprint   string   `json:"fingerprint,omitempty"`
	PinCertSHA256 string   `json:"pcs,omitempty"`
}

// Outbound implements Link
func (v *Vmess) Outbound(opt option.ProviderOutboundsOptions) (*option.Outbound, error) {
	o := &option.VMessOutboundOptions{
		DialerOptions: opt.DialerOptions,
		ServerOptions: option.ServerOptions{
			Server:     v.Server,
			ServerPort: v.Port,
		},
		UUID:     v.UUID,
		AlterId:  v.AlterID,
		Security: v.Security,
	}

	if v.TLS {
		o.TLS = &option.OutboundTLSOptions{
			Enabled:    true,
			Insecure:   v.AllowInsecure,
			ServerName: v.SNI,
			ALPN:       v.ALPN,
		}
		for _, pin := range splitComma(v.PinCertSHA256) {
			decoded, err := hex.DecodeString(pin)
			if err != nil {
				return nil, E.Cause(err, "invalid pcs: ", pin)
			}
			o.TLS.CertificateSHA256 = append(o.TLS.CertificateSHA256, decoded)
		}
		if v.Fingerprint != "" {
			o.TLS.UTLS = &option.OutboundUTLSOptions{
				Enabled:     true,
				Fingerprint: v.Fingerprint,
			}
		}
	}

	topt := &option.V2RayTransportOptions{
		Type: v.Transport,
	}

	switch v.Transport {
	case "":
		topt = nil
	case C.V2RayTransportTypeHTTP:
		topt.HTTPOptions.Path = v.Path
		if v.Host != "" {
			topt.HTTPOptions.Host = []string{v.Host}
			topt.HTTPOptions.Headers = badoption.HTTPHeader{
				"Host": {v.Host},
			}
		}
	case C.V2RayTransportTypeWebsocket:
		topt.WebsocketOptions = v2rayTransportWs(v.Host, v.Path)
	case C.V2RayTransportTypeQUIC:
		// do nothing
	case C.V2RayTransportTypeGRPC:
		topt.GRPCOptions.ServiceName = v.Host
	}

	o.Transport = topt
	return &option.Outbound{
		Type:    C.TypeVMess,
		Tag:     v.Tag,
		Options: o,
	}, nil
}

